"""Development-only fixture pipeline (MOCK_PIPELINE=1). Off by default; never used for acceptance runs.

It replays the repository's validated sample lessons and mock timelines so the frontend can
exercise POST /api/lessons -> poll job -> GET lesson without Ollama, TTS or the renderer.
Every job, lesson response and lesson file is marked mock, the lesson id is derived from the
model name "mock-pipeline" (so it can never collide with a real cached lesson), and a topic
without a fixture is rejected instead of being answered with an unrelated sample.
"""

from __future__ import annotations

import json

from .cache import normalize_topic
from .config import ROOT
from .contracts import LessonRequest
from .jobs import PipelineError
from .orchestrator import MOCK_MODEL, PipelineOps, PipelineRun
from .timeline.schema import RenderProps
from .timeline.srt import render_srt

SAMPLES = ROOT / "data" / "samples"
# fixture file stem -> extra accepted spellings (the fixture's own topic is always accepted)
FIXTURES: dict[str, tuple[str, ...]] = {
    "water_cycle": ("water cycle",),
    "python_loop": ("python loop", "python loops", "python for loop"),
    "newtons_second_law": ("newtons second law", "newton second law"),
}
MOCK_WARNING = "MOCK: fixture lesson from data/samples, not generated by Ollama"


def load_fixture(stem: str) -> RenderProps:
    """Fixture props, validated. The sample timelines carry `voice.engine: "mock"`, which the
    backend Timeline contract does not allow, so a placeholder voice record is substituted
    (voice_id "mock-no-audio"; the timeline has no audio either way)."""
    data = json.loads((SAMPLES / f"{stem}.props.json").read_text(encoding="utf-8"))
    data["timeline"]["voice"] = {"engine": "kokoro", "voice_id": "mock-no-audio", "speed": 1.0}
    return RenderProps.model_validate(data)


def fixture_for(topic: str) -> str | None:
    wanted = normalize_topic(topic)
    for stem, aliases in FIXTURES.items():
        accepted = {normalize_topic(load_fixture(stem).lesson.topic), *map(normalize_topic, aliases)}
        if wanted in accepted:
            return stem
    return None


def precheck(request: LessonRequest) -> None:
    if fixture_for(request.topic) is None:
        raise PipelineError(
            "mock_topic_unavailable",
            "MOCK_PIPELINE=1 has fixtures only for: water cycle, python loop, newtons second law. "
            "Unset MOCK_PIPELINE to plan other topics with Ollama")


def plan(run: PipelineRun) -> None:
    fixture = load_fixture(fixture_for(run.request.topic) or "")
    run.data["fixture"] = fixture
    warnings = [MOCK_WARNING]
    if run.request.level != fixture.lesson.level:
        warnings.append(f"MOCK: fixture level is {fixture.lesson.level}; requested {run.request.level} ignored")
    run.lesson = fixture.lesson.model_copy(update={
        "lesson_id": run.lesson_id, "source": "sample", "model": MOCK_MODEL, "prompt_version": "mock",
        "warnings": warnings})
    run.note("mock fixture")


def validate(run: PipelineRun) -> None:
    run.note("mock: fixture was validated when loaded")  # fixture text is not re-linted against the request


def localize(run: PipelineRun) -> None:
    assert run.lesson is not None
    warnings = [*run.lesson.warnings, f"MOCK: text is English; not translated to {run.language}"]
    run.lesson = run.lesson.model_copy(update={"language": run.language, "warnings": warnings})
    run.note("mock: no translation")


def voice(run: PipelineRun) -> None:
    run.note("mock: no audio")


def timeline(run: PipelineRun) -> None:
    assert run.lesson is not None
    fixture: RenderProps = run.data["fixture"]
    stamped = fixture.timeline.model_copy(update={
        "lesson_id": run.lesson_id, "language": run.language, "variant": run.variant,
        "voice": fixture.timeline.voice.model_copy(update={"speed": run.request.speed})})
    props = RenderProps(lesson=run.lesson, timeline=stamped, mediaBase="", audioVariant="web", showCaptions=True)
    run.folder.mkdir(parents=True, exist_ok=True)
    run.cache.write_json(run.folder / "lesson.json", props.lesson)
    run.cache.write_json(run.folder / "timeline.json", props.timeline)
    run.cache.write_json(run.folder / "props.json", props)
    (run.folder / "lesson.srt").write_text(render_srt(props.timeline), encoding="utf-8")
    run.preview_ready()


def export(run: PipelineRun) -> None:
    run.skip("mock: no MP4 is rendered")


def build_mock_ops() -> PipelineOps:
    return PipelineOps(plan=plan, localize=localize, voice=voice, timeline=timeline, export=export,
                       validate=validate, precheck=precheck, mock=True)
